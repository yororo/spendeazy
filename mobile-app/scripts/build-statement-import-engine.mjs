// Shared production/proof preparation. All PDF.js code/assets are embedded; no CDN.
import { build } from 'esbuild';
import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const dist = path.join(root, 'node_modules/pdfjs-dist');
const assets = {};
const notices = [await readFile(path.join(dist, 'LICENSE'), 'utf8')];
for (const folder of ['cmaps', 'standard_fonts', 'wasm', 'iccs']) {
  for (const name of await readdir(path.join(dist, folder))) {
    if (/license/iu.test(name)) notices.push(await readFile(path.join(dist, folder, name), 'utf8'));
    if (/\.(bcmap|pfb|ttf|wasm|icc)$/u.test(name)) {
      assets[`${folder}/${name}`] = (await readFile(path.join(dist, folder, name))).toString('base64');
    }
  }
}
const worker = await readFile(path.join(dist, 'legacy/build/pdf.worker.mjs'), 'utf8');
const production = await build({
  entryPoints: [path.join(root, 'src/features/statement-import/engine/webview-entry.ts')],
  bundle: true, write: false, format: 'iife', platform: 'browser', target: ['safari16.4', 'chrome110'],
  define: { PROOF_ASSETS: JSON.stringify(assets), PROOF_WORKER: JSON.stringify(worker) },
});
const script = production.outputFiles[0].text.replace(/<\/script/giu, '<\\/script');
const productionHtml = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline' blob:; worker-src blob:; connect-src blob: data:; style-src 'unsafe-inline'; img-src data: blob:; font-src data: blob:"></head><body><script>${script}</script><!-- PDF.js and bundled resource notices:
${notices.join('\n').replace(/-->/gu, '--&gt;')} --></body></html>`;
await mkdir(path.join(root, 'src/features/statement-import/generated'), { recursive: true });
await writeFile(path.join(root, 'src/features/statement-import/generated/html.ts'), `// Generated by npm run statement-import:prepare.\nexport const statementImportHtml = ${JSON.stringify(productionHtml)};\n`);
console.log(`Prepared local PDF.js statement import engine (${Math.round(Buffer.byteLength(productionHtml) / 1024)} KiB).`);
