import { importReducer, matchesOperation, sameOwner, type ImportEvent, type ImportOperation, type ImportOutcome, type ImportState } from './import-state.ts';
import type { ReviewScope } from './review-model.ts';
import type { ReviewEvent } from './review-state.ts';

export type ImportAccess = Readonly<{
  userId: string | null; ownerUserId: string | null; spaceId: string | null;
  generation: number; authenticated: boolean; writable: boolean;
}>;

/** Application lifetime, memory only. Adapters own all transient bytes/passwords. */
export function createImportStore(access: () => ImportAccess) {
  let state: ImportState = { phase: 'idle' };
  const listeners = new Set<() => void>();
  const cleanups = new Set<() => void>();
  function dispatch(event: ImportEvent) {
    const previous = state;
    state = importReducer(state, event);
    if (state === previous) return;
    // Invalidate before notifying adapters to destroy workers and clear secrets.
    if ('operation' in previous && (!('operation' in state) || previous.operation !== state.operation)) {
      const pending = [...cleanups];
      cleanups.clear();
      for (const cleanup of pending) cleanup();
    }
    for (const listener of listeners) listener();
  }
  function allowed(operation: ImportOperation) {
    const scope = access();
    return scope.authenticated && scope.writable && scope.generation === operation.generation &&
      scope.userId === operation.owner.userId && scope.spaceId === operation.owner.spaceId;
  }
  function reviewAllowed(command: ReviewScope, writable: boolean) {
    const scope = access();
    return 'result' in state && state.result !== null && state.phase !== 'suspended' &&
      scope.authenticated && (!writable || scope.writable) && scope.generation === command.generation &&
      scope.userId === command.owner.userId && scope.spaceId === command.owner.spaceId &&
      command.draftId === state.draftId && sameOwner(state.owner, command.owner);
  }
  return {
    snapshot: () => state,
    subscribe(listener: () => void) { listeners.add(listener); return () => { listeners.delete(listener); }; },
    hasWork: () => state.phase !== 'idle',
    captureReview(): ReviewScope | null {
      if (!('result' in state) || !state.result) return null;
      const command = { owner: state.owner, draftId: state.draftId, generation: access().generation };
      return reviewAllowed(command, false) ? command : null;
    },
    initializeReview(command: ReviewScope) {
      if (!reviewAllowed(command, false)) return false;
      dispatch({ type: 'reviewInitialized' });
      return state.phase === 'review' || state.phase === 'review-ready';
    },
    updateReview(command: ReviewScope, event: ReviewEvent) {
      const mutation = ['editorChanged', 'editorAbandoned', 'skipped', 'saved', 'excluded', 'restored', 'continued'].includes(event.type);
      if (!reviewAllowed(command, mutation)) return false;
      if ('request' in event && (event.request.generation !== command.generation ||
        event.request.draftId !== command.draftId || !sameOwner(event.request.owner, command.owner))) return false;
      const previous = state;
      dispatch({ type: 'reviewChanged', event: event.type === 'catalogSucceeded' ? { ...event, applyMatching: access().writable } : event });
      return state !== previous;
    },
    backToReview(command: ReviewScope) {
      if (!reviewAllowed(command, false)) return false;
      dispatch({ type: 'reviewReopened' });
      return state.phase === 'review';
    },
    /** IDs are generated by the controller, outside reducers, uniquely per attempt. */
    start(draftId: string, operation: ImportOperation) {
      if (!allowed(operation)) return false;
      dispatch({ type: 'started', draftId, operation });
      return 'operation' in state && state.operation === operation;
    },
    deliver(operation: ImportOperation, outcome: ImportOutcome) {
      if (allowed(operation)) dispatch({ type: 'outcome', operation, outcome });
    },
    /** Register synchronous secret/reference release; async file cleanup belongs to the adapter. */
    onInvalidate(operation: ImportOperation, cleanup: () => void) {
      if (!allowed(operation) || !('operation' in state) || state.operation !== operation) { cleanup(); return () => {}; }
      cleanups.add(cleanup);
      return () => { cleanups.delete(cleanup); };
    },
    discard() { dispatch({ type: 'discarded' }); },
    cancel(operation: ImportOperation) {
      if (allowed(operation) && matchesOperation(state, operation)) dispatch({ type: 'discarded' });
    },
    synchronize() {
      if (state.phase === 'idle') return;
      const scope = access();
      if (scope.ownerUserId !== state.owner.userId) { dispatch({ type: 'discarded' }); return; }
      if (!scope.authenticated) { dispatch({ type: 'suspended', reason: 'authentication' }); return; }
      const destinationAvailable = sameOwner(state.owner, { userId: scope.userId!, spaceId: scope.spaceId ?? '' });
      if (!destinationAvailable || !scope.writable) {
        // Completed evidence remains inspectable in archived Spaces.
        if (state.phase === 'suspended' && state.result) dispatch({ type: 'recovered' });
        else if (!('result' in state && state.result)) dispatch({ type: 'suspended', reason: 'read-only' });
        return;
      }
      if ('operation' in state && state.operation.generation !== scope.generation) {
        dispatch({ type: 'suspended', reason: 'authentication' });
      }
      dispatch({ type: 'recovered' });
    },
  };
}
