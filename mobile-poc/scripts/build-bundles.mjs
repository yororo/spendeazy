import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const pocRoot = path.resolve(scriptDir, "..");
const webSrc = path.resolve(pocRoot, "../web/src");
const generatedDir = path.join(pocRoot, "src/generated");

mkdirSync(generatedDir, { recursive: true });
mkdirSync(path.join(pocRoot, "assets"), { recursive: true });

const networkGuardBanner = `
globalThis.__pocNetworkEvents = [];
globalThis.__pocRecordNetwork = function (kind, url) {
  var event = { kind: kind, url: String(url) };
  globalThis.__pocNetworkEvents.push(event);
  try {
    var bridge = globalThis.ReactNativeWebView;
    if (bridge && typeof bridge.postMessage === "function") {
      bridge.postMessage(JSON.stringify({
        type: "network",
        kind: event.kind,
        url: event.url,
        count: globalThis.__pocNetworkEvents.length
      }));
    }
  } catch (error) {}
  return event;
};
function __pocIsRemote(value) {
  try {
    var url = new URL(String(value), "file:///parser-webview.html");
    return url.protocol === "http:" || url.protocol === "https:" || url.protocol === "ws:" || url.protocol === "wss:";
  } catch (error) {
    return true;
  }
}
globalThis.fetch = function (input) {
  var url = typeof input === "string" ? input : input instanceof URL ? input.href : input && input.url;
  if (__pocIsRemote(url)) globalThis.__pocRecordNetwork("fetch", url);
  return Promise.reject(new TypeError("Blocked non-local request (fetch): " + url));
};
function __pocBlockedXHR() {}
__pocBlockedXHR.prototype.open = function (_method, url) { this.__url = url; };
__pocBlockedXHR.prototype.setRequestHeader = function () {};
__pocBlockedXHR.prototype.addEventListener = function () {};
__pocBlockedXHR.prototype.abort = function () {};
__pocBlockedXHR.prototype.send = function () {
  if (__pocIsRemote(this.__url)) globalThis.__pocRecordNetwork("xhr", this.__url);
  throw new TypeError("Blocked non-local request (xhr): " + this.__url);
};
globalThis.XMLHttpRequest = __pocBlockedXHR;
globalThis.WebSocket = function (url) {
  globalThis.__pocRecordNetwork("websocket", url);
  throw new TypeError("Blocked non-local request (websocket): " + url);
};
if (globalThis.navigator) {
  globalThis.navigator.sendBeacon = function (url) {
    globalThis.__pocRecordNetwork("beacon", url);
    return false;
  };
}
if (typeof globalThis.EventSource === "function") {
  globalThis.EventSource = function (url) {
    globalThis.__pocRecordNetwork("eventsource", url);
    throw new TypeError("Blocked non-local request (eventsource): " + url);
  };
}
`;

const parserJsPath = path.join(generatedDir, "statement-parser.js");
await esbuild.build({
  entryPoints: [
    path.join(
      webSrc,
      "features/statement-import/statement-parser/transformer.ts",
    ),
  ],
  bundle: true,
  format: "cjs",
  platform: "neutral",
  target: "es2022",
  outfile: parserJsPath,
  alias: { "@": webSrc },
  legalComments: "none",
  banner: {
    js: "/* Generated from web/src statement parsers. Do not edit. */",
  },
});

const webviewJsPath = path.join(pocRoot, "assets/parser-webview.js");
await esbuild.build({
  entryPoints: [path.join(scriptDir, "webview-entry.js")],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2022",
  outfile: webviewJsPath,
  legalComments: "eof",
  minify: true,
  banner: { js: networkGuardBanner },
  define: {
    "process.env.NODE_ENV": '"production"',
  },
});

const webviewJs = readFileSync(webviewJsPath, "utf8");
const html = `<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; connect-src 'none'; img-src 'none'; style-src 'none'; worker-src 'none'; child-src 'none'; frame-src 'none'; object-src 'none';">
<title>On-device statement parser</title>
</head>
<body>
<!--
  pdf-parse 2.4.5 and pdfjs-dist 5.4.296 (Apache-2.0).
  One classic IIFE. globalThis.pdfjsWorker is set inside the bundle.
  No CMap, standard-font, or CDN URLs are configured.
-->
<script>
${webviewJs}
</script>
</body>
</html>
`;

const htmlPath = path.join(pocRoot, "assets/parser-webview.html");
writeFileSync(htmlPath, html);
const htmlModulePath = path.join(generatedDir, "parser-webview-html.ts");
writeFileSync(
  htmlModulePath,
  `// Generated by scripts/build-bundles.mjs. Do not edit.\nexport const parserWebViewHtml = ${JSON.stringify(html)};\n`,
);

const sha256 = createHash("sha256").update(html).digest("hex");
const parserSha = createHash("sha256").update(readFileSync(parserJsPath)).digest("hex");
writeFileSync(
  path.join(generatedDir, "bundle-manifest.json"),
  JSON.stringify(
    {
      pdfParse: "2.4.5",
      pdfjsDist: "5.4.296",
      parserBundleSha256: parserSha,
      webViewHtmlSha256: sha256,
      webViewHtmlBytes: Buffer.byteLength(html),
    },
    null,
    2,
  ) + "\n",
);

const parserSource = readFileSync(parserJsPath, "utf8");
const forbidden = ["createApiClient", "@clerk/", "cdn.jsdelivr.net"];
for (const token of forbidden) {
  if (parserSource.includes(token)) {
    throw new Error(`Parser bundle contains forbidden token: ${token}`);
  }
}

console.log(
  `Wrote parser bundle (${parserSource.length} bytes) and WebView HTML (${html.length} bytes, sha256 ${sha256}).`,
);
